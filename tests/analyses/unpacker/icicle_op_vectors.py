# Known-answer vectors for the x86 instructions the Icicle engine implements with user-op helpers or patched SLEIGH.
# Each entry is (64-bit mode, code, data kind, digest[, compared flags]); the digests were taken from a host CPU
# (64-bit entries) or from Unicorn, for the states make_state() derives from the code bytes.
from __future__ import annotations

import hashlib
import random
import struct

CODE, DATA, DSIZE = 0x10000000, 0x20000000, 0x2000
P_OFF, Q_OFF, SP_OFF = 0x800, 0x1000, 0x1F00
_INTS = (0, 1, 0x7F, 0x80, 0xFF, 0x7FFF, 0x8000, 0xFFFF, 0x7FFFFFFF, 0x80000000, 0xFFFFFFFF, 0x1F, 0x20, 0x3F, 0x40)
_FLOATS = (0.0, -0.0, 1.0, -1.0, 0.5, 1.5, 2.5, -2.5, 3.0, 1e10, -1e10, 1e-10, 3.0e38, float("inf"), -float("inf"),
           16777216.0, 0.1, 100.25, -7.75, 2147483648.0, -2147483904.0, float("nan"))  # fmt: skip


def _vector(rnd: random.Random, kind: str) -> int:
    if kind == "f":
        raw = struct.pack(
            "<4f", *(rnd.choice(_FLOATS) if rnd.random() < 0.6 else rnd.uniform(-1000, 1000) for _ in range(4))
        )
    elif kind == "d":
        raw = struct.pack(
            "<2d", *(rnd.choice(_FLOATS) if rnd.random() < 0.6 else rnd.uniform(-1e6, 1e6) for _ in range(2))
        )
    elif kind == "s":
        n = rnd.randrange(0, 17)
        raw = bytes(rnd.choice(b"abcdefxyz AB01") for _ in range(n)) + bytes(16 - n)
    else:
        mode = rnd.randrange(5)
        if mode == 0:
            raw = rnd.randbytes(16)
        elif mode == 1:
            raw = bytes(rnd.choice((0, 1, 0x7F, 0x80, 0xFF, 0xFE, 0x81)) for _ in range(16))
        elif mode == 2:
            raw = b"".join(
                struct.pack("<H", rnd.choice((0, 1, 0x7FFF, 0x8000, 0xFFFF, 0x8001, 0xFF, 0x100))) for _ in range(8)
            )
        elif mode == 3:
            raw = b"".join(
                struct.pack("<I", rnd.choice((0, 1, 0x7FFFFFFF, 0x80000000, 0xFFFFFFFF, 0xFFFF, 0x10000)))
                for _ in range(4)
            )
        else:
            raw = bytes(rnd.randrange(0, 20) for _ in range(16))
    return int.from_bytes(raw, "little")


def make_state(key: str, is64: bool, kind: str) -> tuple[list[int], int, list[int], bytes]:
    """(general registers in encoding order, flags, xmm registers, data memory) for a test key."""
    rnd = random.Random(key)
    count, bits = (16, 64) if is64 else (8, 32)
    gpr = [rnd.getrandbits(bits) if rnd.random() < 0.5 else rnd.choice(_INTS) for _ in range(count)]
    gpr[4], gpr[6], gpr[7] = DATA + SP_OFF, DATA + P_OFF, DATA + Q_OFF
    mem = bytearray(rnd.randbytes(DSIZE))
    for off in (P_OFF, Q_OFF):
        for i in range(0, 64, 16):
            mem[off + i : off + i + 16] = _vector(rnd, kind).to_bytes(16, "little")
    xmm = [_vector(rnd, kind) for _ in range(count)]
    return gpr, rnd.getrandbits(12) & 0x8D5, xmm, bytes(mem)


def digest(results: list[tuple[list[int], int, list[int], bytes]], flags_mask: int) -> str:
    """Digest of the visible outcome of some runs: registers but the stack pointer, flags, xmm, the two data areas."""
    h = hashlib.blake2b(digest_size=6)
    for gpr, flags, xmm, mem in results:
        for i, value in enumerate(gpr):
            if i != 4:
                h.update(value.to_bytes(8, "little"))
        h.update((flags & flags_mask).to_bytes(4, "little"))
        for value in xmm:
            h.update(value.to_bytes(16, "little"))
        h.update(mem[P_OFF : P_OFF + 0x80])
        h.update(mem[Q_OFF : Q_OFF + 0x80])
    return h.hexdigest()


